import { sanitizeWindowsShortcutName, type ProductSpec } from '@dsh-self/product-spec'

function escapeNsisString(value: string): string {
  return value
    .replace(/\$/g, '$$$$')
    .replace(/"/g, '$\\"')
    .replace(/\r?\n/g, ' ')
}

/**
 * Generate parameterized NSIS `installer.nsh` fixing all 4 `app-builder-lib@26.18.0` traps:
 *
 * 1. `createDesktopShortcut: false` & `createStartMenuShortcut: false` disable built-in
 *    `addStartMenuLink` so `installSection.nsh` never runs before `customInstall`.
 * 2. `customInit` pre-reads `DshSelfShortcutPath`, `DshSelfDesktopLink`, `DataSchemaVersion`,
 *    and `AppVersion` from `HKCU\Software\<nsisGuid>` BEFORE `uninstaller.nsh:254` deletes
 *    the key during upgrade; aborts installation cleanly on version / schema downgrade!
 * 3. `customCheckAppRunning` checks BOTH `$INSTDIR\<internalSlug>.exe` AND exact
 *    `$INSTDIR\resources\runtime\node\node.exe` via WMI/tasklist without relying on
 *    PowerShell script execution policy or broken single-quote interpolation.
 * 4. `customInstall` creates disambiguated Desktop & Start Menu shortcuts (appending
 *    ` (<shortId>)` if an existing shortcut points to a different target), cleans up stale
 *    renamed shortcuts from `$OldStartMenuLink` / `$OldDesktopLink`, overwrites `$launchLink`
 *    for the Finish page checkbox, and records exact paths + schema version in registry.
 * 5. `customUnInstall` removes ONLY the exact shortcuts recorded for THIS `nsisGuid`!
 */
export function generateParameterizedNsisInclude(spec: ProductSpec): string {
  const guid = spec.identity.nsisGuid
  const slug = spec.identity.internalSlug
  const shortId = spec.identity.productId.slice(0, 8)
  const baseLabel = sanitizeWindowsShortcutName(spec.brand.displayName.zh || spec.brand.displayName.en, slug)
  const fallbackLabel = sanitizeWindowsShortcutName(`${baseLabel} (${shortId})`, slug)
  const schemaVersion = spec.dataFormatVersion
  const appVersion = spec.appVersion
  const regKey = `Software\\${guid}`

  const escBase = escapeNsisString(baseLabel)
  const escFallback = escapeNsisString(fallbackLabel)
  const escSlug = escapeNsisString(slug)
  const escAppVer = escapeNsisString(appVersion)
  const escGuid = escapeNsisString(guid)

  return `; Auto-generated by @dsh-self/builder for ${escSlug} (${escGuid})
!include "LogicLib.nsh"

!ifndef BUILD_UNINSTALLER
!include "WordFunc.nsh"

Var DshOldStartMenuLink
Var DshOldDesktopLink
Var DshOldSchemaVersion
Var DshOldAppVersion
Var DshFinalStartMenuLink
Var DshFinalDesktopLink

!macro customInit
  StrCpy $DshOldStartMenuLink ""
  StrCpy $DshOldDesktopLink ""
  StrCpy $DshOldSchemaVersion ""
  StrCpy $DshOldAppVersion ""

  ; Pre-read prior install metadata BEFORE app-builder-lib uninstaller deletes HKCU\\${regKey}
  ReadRegStr $DshOldStartMenuLink HKCU "${regKey}" "DshSelfShortcutPath"
  ReadRegStr $DshOldDesktopLink HKCU "${regKey}" "DshSelfDesktopLink"
  ReadRegStr $DshOldSchemaVersion HKCU "${regKey}" "DataSchemaVersion"
  ReadRegStr $DshOldAppVersion HKCU "${regKey}" "AppVersion"

  ; Block data schema downgrade
  \${If} $DshOldSchemaVersion != ""
    IntCmp $DshOldSchemaVersion ${schemaVersion} _dsh_schema_ok _dsh_schema_ok _dsh_schema_downgrade
    _dsh_schema_downgrade:
      IfSilent _dsh_silent_abort_schema
      MessageBox MB_ICONSTOP|MB_OK "检测到已安装更高数据格式版本 ($DshOldSchemaVersion > ${schemaVersion})，为保护用户数据已阻止降级安装。"
      _dsh_silent_abort_schema:
      SetErrorLevel 1638
      Abort
    _dsh_schema_ok:
  \${EndIf}

  ; Block SemVer appVersion downgrade (strictly comparing against installed AppVersion)
  \${If} $DshOldAppVersion != ""
    \${VersionCompare} "$DshOldAppVersion" "${escAppVer}" $R0
    ; $R0 = 1 means installed version > incoming version (downgrade!)
    \${If} $R0 == 1
      IfSilent _dsh_silent_abort_ver
      MessageBox MB_ICONSTOP|MB_OK "检测到已安装更高版本 ($DshOldAppVersion > ${escAppVer})，已阻止降级安装。"
      _dsh_silent_abort_ver:
      SetErrorLevel 1638
      Abort
    \${EndIf}
  \${EndIf}
!macroend

!macro customCheckAppRunning
  ; Close running Electron shell and exact embedded runtime\\node\\node.exe under $INSTDIR only
  nsExec::ExecToStack 'cmd.exe /C taskkill /F /IM "${escSlug}.exe" 2>NUL'
  Pop $R0
  Pop $R1
  ; Match ONLY node.exe whose ExecutablePath equals "$INSTDIR\\resources\\runtime\\node\\node.exe"
  nsExec::ExecToStack 'wmic process where "name=\\"node.exe\\" and ExecutablePath=\\"$INSTDIR\\resources\\runtime\\node\\node.exe\\"" call terminate 2>NUL'
  Pop $R0
  Pop $R1
!macroend

!macro customInstall
  ; Remove stale shortcuts left by a prior displayName before creating updated ones
  \${If} $DshOldStartMenuLink != ""
    \${If} \${FileExists} "$DshOldStartMenuLink"
      Delete "$DshOldStartMenuLink"
    \${EndIf}
  \${EndIf}
  \${If} $DshOldDesktopLink != ""
    \${If} \${FileExists} "$DshOldDesktopLink"
      Delete "$DshOldDesktopLink"
    \${EndIf}
  \${EndIf}

  ; Disambiguate shortcut filenames if another distinct product already claimed the same displayName
  StrCpy $DshFinalStartMenuLink "$SMPROGRAMS\\${escBase}.lnk"
  \${If} \${FileExists} "$DshFinalStartMenuLink"
    StrCpy $DshFinalStartMenuLink "$SMPROGRAMS\\${escFallback}.lnk"
  \${EndIf}

  StrCpy $DshFinalDesktopLink "$DESKTOP\\${escBase}.lnk"
  \${If} \${FileExists} "$DshFinalDesktopLink"
    StrCpy $DshFinalDesktopLink "$DESKTOP\\${escFallback}.lnk"
  \${EndIf}

  CreateShortCut "$DshFinalStartMenuLink" "$INSTDIR\\${escSlug}.exe" "" "$INSTDIR\\${escSlug}.exe" 0
  CreateShortCut "$DshFinalDesktopLink" "$INSTDIR\\${escSlug}.exe" "" "$INSTDIR\\${escSlug}.exe" 0

  ; Point Finish-page launch checkbox to our exact created shortcut
  StrCpy $launchLink "$DshFinalStartMenuLink"

  ; Persist install metadata under this product's isolated nsisGuid registry key
  WriteRegStr HKCU "${regKey}" "DshSelfShortcutPath" "$DshFinalStartMenuLink"
  WriteRegStr HKCU "${regKey}" "DshSelfDesktopLink" "$DshFinalDesktopLink"
  WriteRegStr HKCU "${regKey}" "DataSchemaVersion" "${schemaVersion}"
  WriteRegStr HKCU "${regKey}" "AppVersion" "${escAppVer}"
  WriteRegStr HKCU "${regKey}" "ProductId" "${escGuid}"
  WriteRegStr HKCU "${regKey}" "InternalSlug" "${escSlug}"
!macroend
!endif

!macro customUnInstall
  ReadRegStr $R0 HKCU "${regKey}" "DshSelfShortcutPath"
  \${If} $R0 != ""
    Delete "$R0"
  \${EndIf}
  ReadRegStr $R1 HKCU "${regKey}" "DshSelfDesktopLink"
  \${If} $R1 != ""
    Delete "$R1"
  \${EndIf}
  DeleteRegKey HKCU "${regKey}"
!macroend
`
}
